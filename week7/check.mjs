import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
const file=await readFile(new URL('./public/models/RobotExpressive.glb',import.meta.url));
assert.equal(file.toString('ascii',0,4),'glTF');
const gltf=await new GLTFLoader().parseAsync(file.buffer.slice(file.byteOffset,file.byteOffset+file.byteLength),'');
let meshes=0,skinned=0;
gltf.scene.traverse(node=>{if(node.isMesh)meshes++;if(node.isSkinnedMesh)skinned++;});
assert(meshes>0 && skinned>0,'GLB must contain rendered and skinned meshes');
assert(gltf.animations.length>=2,'multiple animation clips');
const mixer=new THREE.AnimationMixer(gltf.scene);
const clip=gltf.animations.find(clip=>clip.name==='Walking');
assert(clip,'Walking clip exists');
mixer.clipAction(clip).play();mixer.update(.25);
assert.equal(mixer.time,.25);
const parent=new THREE.Group();parent.add(gltf.scene);gltf.scene.position.set(-2,0,0);
parent.updateMatrixWorld(true);
const before=gltf.scene.getWorldPosition(new THREE.Vector3());
parent.rotation.y=Math.PI/2;parent.updateMatrixWorld(true);
assert.equal(gltf.scene.position.x,-2);
assert(gltf.scene.getWorldPosition(new THREE.Vector3()).distanceTo(before)>1);
console.log(`PASS: valid GLB, ${meshes} meshes, ${skinned} skinned meshes, ${gltf.animations.length} clips, mixer and local/world transforms`);
